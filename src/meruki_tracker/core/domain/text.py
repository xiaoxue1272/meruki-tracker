"""把"远端的文字"变成"可以给终端看的文字"。

拍品名、描述、卖家昵称都是别人填的，而终端把 ESC 之后的内容当**指令**执行：
一个叫 ``\\x1b[2J`` 的标题能让整屏被清掉，``\\x1b]0;xxx\\x07`` 能改终端标题。
这类注入比崩溃更难查——程序不报错、状态也没错，只是屏幕上少了一块。

规则（唯一的一条）：

- 保留 ``\\n`` 与 ``\\t``：描述本来就是多行、带缩进的，抹掉会把段落挤成一坨；
- 其余 C0（``0x00–0x1F``）、DEL（``0x7F``）、C1（``0x80–0x9F``）全部删掉。
  它们对"读一段文字"没有任何贡献，却全都能改变终端行为。
"""

from __future__ import annotations

import re

#: C0 控制字符（去掉 ``\t``=0x09 与 ``\n``=0x0A）、DEL、C1。
_CONTROL_RE = re.compile(r"[\x00-\x08\x0b-\x1f\x7f-\x9f]")


def scrub(text: str) -> str:
    """删掉会驱动终端的控制字符，其余原样保留。

    Args:
        text: 任何来自接口/库里的字符串。

    Returns:
        把 C0（除 ``\\n`` ``\\t``）、DEL、C1 删掉之后的字符串。

    >>> scrub("清屏\\x1b[2J保留")
    '清屏[2J保留'
    """
    if not text:
        return ""
    return _CONTROL_RE.sub("", text)
